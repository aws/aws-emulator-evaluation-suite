"""disable-alarm-actions-toggle-recorded-in-alarm-history."""
from __future__ import annotations

import time

from behavioral_harness import tags

CHECK = "disable-alarm-actions-toggle-recorded-in-alarm-history"
GROUP = "telemetry"
SERVICES = ["cloudwatch"]


@tags("axis:happy-path", "cap:c2", "concern:representation", "plane:control")
def run(ctx) -> None:
    """Toggling actions-enabled via Disable/EnableAlarmActions produces a
    distinct ConfigurationUpdate entry in DescribeAlarmHistory, separate from
    the StateUpdate history generated by an actual alarm state transition."""
    cw = ctx.client("cloudwatch")
    alarm_name = ctx.unique_name("sim2real-cw-alarm-")
    cw.put_metric_alarm(
        AlarmName=alarm_name,
        Namespace=ctx.unique_name("sim2real-cw-ns-"),
        MetricName="ActionsHistoryTest",
        Statistic="Average",
        Period=60,
        EvaluationPeriods=1,
        Threshold=1.0,
        ComparisonOperator="GreaterThanThreshold",
        Tags=[{"Key": "sim2real-check", "Value": CHECK}],
    )
    ctx.on_cleanup(lambda: cw.delete_alarms(AlarmNames=[alarm_name]))

    # Produce a state-change history entry for contrast with the config toggle.
    cw.set_alarm_state(AlarmName=alarm_name, StateValue="ALARM", StateReason="behavioral-test")

    def _config_items():
        return cw.describe_alarm_history(
            AlarmName=alarm_name, HistoryItemType="ConfigurationUpdate"
        )["AlarmHistoryItems"]

    def _key(item):
        return (item["Timestamp"], item["HistorySummary"], item.get("HistoryData", ""))

    # New entries are those absent before the call; the runner's clock is never compared with
    # the server's Timestamp, so clock skew cannot drop or admit an entry.
    before_disable = {_key(i) for i in _config_items()}
    cw.disable_alarm_actions(AlarmNames=[alarm_name])
    actions_after_disable = cw.describe_alarms(AlarmNames=[alarm_name])["MetricAlarms"][0]["ActionsEnabled"]
    assert actions_after_disable is False, (
        f"expected ActionsEnabled False after DisableAlarmActions, got {actions_after_disable!r}"
    )

    def _config_entries_since(seen):
        return [i for i in _config_items() if _key(i) not in seen]

    def _mentions_action(items):
        return any(
            "action" in i["HistorySummary"].lower() or "action" in i.get("HistoryData", "").lower()
            for i in items
        )

    disable_entries = _poll_until(
        lambda: _config_entries_since(before_disable), _mentions_action, timeout_s=60.0, interval_s=3.0
    )
    assert all(i["HistoryItemType"] == "ConfigurationUpdate" for i in disable_entries), (
        f"expected only ConfigurationUpdate items in the disable-actions window, got {disable_entries!r}"
    )

    before_enable = {_key(i) for i in _config_items()}
    cw.enable_alarm_actions(AlarmNames=[alarm_name])
    actions_after_enable = cw.describe_alarms(AlarmNames=[alarm_name])["MetricAlarms"][0]["ActionsEnabled"]
    assert actions_after_enable is True, (
        f"expected ActionsEnabled True after EnableAlarmActions, got {actions_after_enable!r}"
    )

    _poll_until(
        lambda: _config_entries_since(before_enable), _mentions_action, timeout_s=60.0, interval_s=3.0
    )

    # The state transition is recorded separately under StateUpdate, never
    # commingled with the ConfigurationUpdate entries produced by the toggles.
    state_entries = cw.describe_alarm_history(AlarmName=alarm_name, HistoryItemType="StateUpdate")[
        "AlarmHistoryItems"
    ]
    assert len(state_entries) >= 1, "expected at least the earlier SetAlarmState to have a StateUpdate entry"
    assert all(i["HistoryItemType"] == "StateUpdate" for i in state_entries), (
        f"describe_alarm_history(HistoryItemType='StateUpdate') returned a non-StateUpdate item: {state_entries!r}"
    )
    assert not any("action" in i["HistorySummary"].lower() for i in state_entries), (
        f"StateUpdate history must never mention actions toggles, got {state_entries!r}"
    )


def _poll_until(probe, predicate, timeout_s=60.0, interval_s=2.0):
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        last = probe()
        if predicate(last):
            return last
        time.sleep(interval_s)
    raise AssertionError(f"condition not met within {timeout_s}s (last={last!r})")


if __name__ == "__main__":
    from fidelity_tests_runner import main
    main(run)
