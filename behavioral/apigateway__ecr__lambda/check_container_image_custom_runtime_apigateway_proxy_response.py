def _budget_s(ctx, cap_s):
    """A poll's timeout: cap_s, bounded by the runner's remaining time less 5 s so the poll fails
    with its own message."""
    left = ctx.time_left()
    return cap_s if left is None else max(1.0, min(cap_s, left - 5.0))


def _budget_spent(ctx):
    """True when the runner's remaining time, not the wait's own deadline, ended a capped wait."""
    left = ctx.time_left()
    return left is not None and left <= 6.0


def _teardown(undo, *not_found: str):
    """A cleanup running ``undo()`` where a failed delete raises (not-found codes excepted)."""

    def run_undo() -> None:
        try:
            undo()
        except ClientError as exc:
            if exc.response["Error"]["Code"] in not_found:
                return
            raise

    return run_undo


def _reap_log_group(logs, name: str, *, reads: int = 3, interval_s: float = 5.0,
                    budget_s: float = 150.0) -> None:
    """Delete log group ``name`` until ``reads`` consecutive reads find it absent. A log stream
    flushed after delete_function can recreate the group, so one delete is not a teardown."""
    deadline = time.monotonic() + budget_s
    absent = 0
    while absent < reads:
        groups = logs.describe_log_groups(logGroupNamePrefix=name)["logGroups"]
        if any(g["logGroupName"] == name for g in groups):
            absent = 0
            try:
                logs.delete_log_group(logGroupName=name)
            except ClientError as exc:
                if exc.response["Error"]["Code"] != "ResourceNotFoundException":
                    raise
        else:
            absent += 1
        if absent < reads:
            if time.monotonic() > deadline:
                raise AssertionError(
                    f"log group {name} still present after {budget_s}s of deletes"
                )
            time.sleep(interval_s)


def _execution_role(ctx, iam, managed_policy_arns=None, inline_statements=None) -> str:
    role_name = ctx.unique_name("sim2real-xsvc-cir-role-")
    trust = {
        "Version": "2012-10-17",
        "Statement": [{
            "Effect": "Allow",
            "Principal": {"Service": "lambda.amazonaws.com"},
            "Action": "sts:AssumeRole",
        }],
    }
    role_arn = iam.create_role(
        RoleName=role_name, AssumeRolePolicyDocument=json.dumps(trust),
        Tags=[{"Key": "sim2real", "Value": CHECK}],
    )["Role"]["Arn"]
    ctx.on_cleanup(lambda: _delete_role(iam, role_name))
    for arn in managed_policy_arns or []:
        iam.attach_role_policy(RoleName=role_name, PolicyArn=arn)
    if inline_statements:
        iam.put_role_policy(
            RoleName=role_name, PolicyName="inline",
            PolicyDocument=json.dumps({"Version": "2012-10-17", "Statement": inline_statements}),
        )
    return role_name, role_arn


def _delete_role(iam, role_name: str) -> None:
    try:
        for p in iam.list_attached_role_policies(RoleName=role_name).get("AttachedPolicies", []):
            iam.detach_role_policy(RoleName=role_name, PolicyArn=p["PolicyArn"])
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "NoSuchEntity":
            raise
    try:
        for name in iam.list_role_policies(RoleName=role_name).get("PolicyNames", []):
            iam.delete_role_policy(RoleName=role_name, PolicyName=name)
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "NoSuchEntity":
            raise
    try:
        iam.delete_role(RoleName=role_name)
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "NoSuchEntity":
            raise


def _create_function(ctx, lam, timeout_s=90.0, **kwargs) -> dict:
    """CreateFunction, retried only while the freshly created role is not yet assumable."""
    timeout_s = _budget_s(ctx, timeout_s)
    deadline = time.monotonic() + timeout_s
    while True:
        try:
            return lam.create_function(**kwargs)
        except ClientError as exc:
            err = exc.response.get("Error", {})
            propagating = err.get("Code") == "InvalidParameterValueException" and (
                "cannot be assumed" in err.get("Message", "")
            )
            if not propagating or time.monotonic() >= deadline:
                if propagating and _budget_spent(ctx):
                    raise TimeoutError(
                        "CreateFunction: the run budget ended first while the execution role "
                        "was still propagating; not graded"
                    ) from exc
                raise
            time.sleep(2.0)


def _wait_active(ctx, lam, fn: str, timeout_s=240.0) -> dict:
    timeout_s = _budget_s(ctx, timeout_s)
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        last = lam.get_function_configuration(FunctionName=fn)
        if last["State"] == "Failed":
            raise AssertionError(
                f"{fn} reached State=Failed: {last.get('StateReasonCode')!r} "
                f"{last.get('StateReason')!r}"
            )
        if last["State"] == "Active":
            return last
        time.sleep(2.0)
    if _budget_spent(ctx):
        raise TimeoutError(
            f"{fn} stayed State={last and last.get('State')!r}: the run budget ended first; not graded"
        )
    raise AssertionError(f"{fn} stayed State={last and last.get('State')!r} for {timeout_s}s")


def _c(fn, **kw):
    """Call an apigateway control-plane op, retrying only its per-account mutation throttle."""
    for attempt in range(10):
        try:
            return fn(**kw)
        except ClientError as exc:
            if exc.response.get("Error", {}).get("Code") != "TooManyRequestsException" or attempt == 9:
                raise
            time.sleep(min(4.0, 0.3 * (2 ** attempt)))
    raise RuntimeError("unreachable")


def _ssl_context(verify):
    """An SSLContext honouring ``ctx.http_verify``: True, False, or a CA bundle path."""
    if verify is False:
        return ssl._create_unverified_context()
    return ssl.create_default_context(cafile=verify if isinstance(verify, str) else None)


def _raw_request(url, method, body, verify):
    u = urllib.parse.urlsplit(url)
    if u.scheme == "https":
        conn = http.client.HTTPSConnection(u.netloc, timeout=25, context=_ssl_context(verify))
    else:
        conn = http.client.HTTPConnection(u.netloc, timeout=25)
    try:
        path = u.path + (f"?{u.query}" if u.query else "")
        conn.request(method, path, body=body)
        resp = conn.getresponse()
        return resp.status, resp.read().decode("utf-8", "replace")
    finally:
        conn.close()


def _raw_request_headers(url, method, body, verify):
    u = urllib.parse.urlsplit(url)
    if u.scheme == "https":
        conn = http.client.HTTPSConnection(u.netloc, timeout=25, context=_ssl_context(verify))
    else:
        conn = http.client.HTTPConnection(u.netloc, timeout=25)
    try:
        path = u.path + (f"?{u.query}" if u.query else "")
        conn.request(method, path, body=body)
        resp = conn.getresponse()
        text = resp.read().decode("utf-8", "replace")
        return resp.status, text, {k.lower(): v for k, v in resp.getheaders()}
    finally:
        conn.close()


def _poll(ctx, probe, predicate, description, timeout_s=150.0, interval_s=2.0):
    """Poll probe() to a condition, tolerating connection errors while execute-api DNS settles."""
    timeout_s = _budget_s(ctx, timeout_s)
    deadline = time.monotonic() + timeout_s
    last = None
    while True:
        try:
            last = probe()
        except OSError as exc:
            last = ("connection error", repr(exc))
        else:
            if predicate(last):
                return last
        if time.monotonic() >= deadline:
            if _budget_spent(ctx):
                raise TimeoutError(f"{description}: the run budget ended first; not graded")
            raise AssertionError(f"{description}: condition not met within {timeout_s}s; last {last!r}")
        time.sleep(interval_s)


@tags("axis:happy-path", "cap:c3", "concern:data-plane", "concern:e2e", "dp:endpoint",
      "plane:data")
def run(ctx) -> None:
    """A REST API AWS_PROXY integration hands a container-image function's custom (non-Python)
    runtime the request method, path, query string and body, and its
    statusCode/headers/body shape the HTTP response returned to the client.

    Reference: https://docs.aws.amazon.com/apigateway/latest/developerguide/set-up-lambda-proxy-integrations.html
    """
    ecr = ctx.client("ecr")
    iam = ctx.client("iam")
    lam = ctx.client("lambda")
    ag = ctx.client("apigateway")
    logs = ctx.client("logs")

    repo, repo_uri = _create_repo(ctx, ecr)
    built = _build_and_push_image(ecr, repo, repo_uri, "v1")
    _, role_arn = _execution_role(ctx, iam)

    fn = ctx.unique_name("sim2real-xsvc-cir-fn-")
    created = _create_function(
        ctx, lam, FunctionName=fn, PackageType="Image", Role=role_arn,
        Code={"ImageUri": built["uri"]}, Timeout=10, MemorySize=256,
        Tags={"sim2real": CHECK},
    )
    fn_arn = created["FunctionArn"]
    ctx.on_cleanup(lambda: _reap_log_group(logs, f"/aws/lambda/{fn}"))
    ctx.on_cleanup(_teardown(lambda: lam.delete_function(FunctionName=fn), "ResourceNotFoundException"))
    cfg = _wait_active(ctx, lam, fn)
    assert "CodeSha256" in cfg, f"GetFunctionConfiguration omits CodeSha256: {cfg!r}"
    assert cfg["CodeSha256"] == built["manifest_digest"].split(":", 1)[1], (
        f"CodeSha256 {cfg['CodeSha256']!r} is not the manifest digest hex we pushed "
        f"({built['manifest_digest'].split(':', 1)[1]!r})"
    )

    api_id = _c(ag.create_rest_api, name=ctx.unique_name("sim2real-xsvc-cir-api-"),
                endpointConfiguration={"types": ["REGIONAL"]},
                tags={"sim2real": CHECK})["id"]
    ctx.on_cleanup(_teardown(lambda: _c(ag.delete_rest_api, restApiId=api_id), "NotFoundException"))
    root_id = next(r["id"] for r in ag.get_resources(restApiId=api_id)["items"] if r["path"] == "/")
    proxy_id = _c(ag.create_resource, restApiId=api_id, parentId=root_id, pathPart="{proxy+}")["id"]
    _c(ag.put_method, restApiId=api_id, resourceId=proxy_id, httpMethod="ANY",
       authorizationType="NONE")
    integ_uri = (
        f"arn:aws:apigateway:{ctx.region}:lambda:path/2015-03-31/functions/{fn_arn}/invocations"
    )
    _c(ag.put_integration, restApiId=api_id, resourceId=proxy_id, httpMethod="ANY",
       type="AWS_PROXY", integrationHttpMethod="POST", uri=integ_uri)

    lam.add_permission(
        FunctionName=fn, StatementId="sim2real-apigw-invoke", Action="lambda:InvokeFunction",
        Principal="apigateway.amazonaws.com",
        SourceArn=f"arn:aws:execute-api:{ctx.region}:{ctx.account}:{api_id}/*/*",
    )

    stage = "live"
    dep_id = _c(ag.create_deployment, restApiId=api_id)["id"]
    _c(ag.create_stage, restApiId=api_id, stageName=stage, deploymentId=dep_id)
    ctx.on_cleanup(_teardown(lambda: _c(ag.delete_stage, restApiId=api_id, stageName=stage),
                             "NotFoundException"))

    base_url = ctx.rest_api_url(api_id, stage)

    status, text = _poll(
        ctx, lambda: _raw_request(f"{base_url}/sim2real/widgets?q=zorp", "GET", None, ctx.http_verify),
        lambda r: r[0] in (200, 222), "GET through the deployed stage",
    )
    assert status == 222, f"GET response status {status!r}, expected 222: {text[:300]!r}"
    seen = json.loads(text)
    assert seen["seen_method"] == "GET", f"handler saw httpMethod {seen['seen_method']!r}, expected 'GET'"
    assert seen["seen_path"] == "/sim2real/widgets", (
        f"handler saw path {seen['seen_path']!r}, expected '/sim2real/widgets'"
    )
    assert seen["seen_q"] == "zorp", f"handler saw query param q={seen['seen_q']!r}, expected 'zorp'"
    assert seen["seen_body"] == "", f"a GET with no body should see seen_body=='', got {seen['seen_body']!r}"

    status, text, headers = _raw_request_headers(
        f"{base_url}/sim2real/widgets", "POST", "hello-body", ctx.http_verify)
    assert status == 222, f"POST response status {status!r}, expected 222: {text[:300]!r}"
    assert headers.get("x-sim2real-handler") == "c-static", (
        f"response headers {headers!r} missing the handler's own 'x-sim2real-handler: c-static'"
    )
    seen = json.loads(text)
    assert seen["seen_method"] == "POST", f"handler saw httpMethod {seen['seen_method']!r}, expected 'POST'"
    assert seen["seen_body"] == "hello-body", (
        f"handler saw body {seen['seen_body']!r}, expected 'hello-body'"
    )


if __name__ == "__main__":
    from fidelity_tests_runner import main

    main(run)
