def _decode_bootstrap() -> bytes:
    raw = gzip.decompress(base64.b64decode(_BOOTSTRAP_GZ_B64))
    digest = hashlib.sha256(raw).hexdigest()
    assert digest == _BOOTSTRAP_SHA256, (
        f"embedded bootstrap decoded to sha256={digest!r}, expected {_BOOTSTRAP_SHA256!r}"
    )
    return raw


def _digest(data: bytes) -> str:
    return f"sha256:{hashlib.sha256(data).hexdigest()}"


def _push_blob(ecr, repo: str, data: bytes) -> str:
    digest = _digest(data)
    upload_id = ecr.initiate_layer_upload(repositoryName=repo)["uploadId"]
    ecr.upload_layer_part(
        repositoryName=repo, uploadId=upload_id, partFirstByte=0,
        partLastByte=len(data) - 1, layerPartBlob=data,
    )
    ecr.complete_layer_upload(repositoryName=repo, uploadId=upload_id, layerDigests=[digest])
    return digest


def _build_and_push_image(ecr, repo: str, repo_uri: str, tag: str) -> dict:
    """A FROM-scratch, single-layer linux/amd64 image: no base OS, the bootstrap binary is PID 1."""
    bootstrap = _decode_bootstrap()
    raw_tar = io.BytesIO()
    with tarfile.open(fileobj=raw_tar, mode="w") as tar:
        info = tarfile.TarInfo("bootstrap")
        info.size = len(bootstrap)
        info.mode = 0o755
        info.mtime = 0
        tar.addfile(info, io.BytesIO(bootstrap))
    tar_bytes = raw_tar.getvalue()
    gz = gzip.compress(tar_bytes, compresslevel=6, mtime=0)
    layer_digest = _push_blob(ecr, repo, gz)
    config = {
        "architecture": "amd64", "os": "linux",
        "config": {"Entrypoint": ["/bootstrap"], "WorkingDir": "/"},
        "rootfs": {"type": "layers", "diff_ids": [_digest(tar_bytes)]},
    }
    config_bytes = json.dumps(config, separators=(",", ":")).encode()
    config_digest = _push_blob(ecr, repo, config_bytes)
    manifest = {
        "schemaVersion": 2, "mediaType": _MANIFEST_V2,
        "config": {"mediaType": _CONFIG_MEDIA, "size": len(config_bytes), "digest": config_digest},
        "layers": [{"mediaType": _LAYER_MEDIA, "size": len(gz), "digest": layer_digest}],
    }
    man_bytes = json.dumps(manifest, separators=(",", ":")).encode()
    ecr.put_image(
        repositoryName=repo, imageManifest=man_bytes.decode(),
        imageManifestMediaType=_MANIFEST_V2, imageTag=tag,
    )
    return {"uri": f"{repo_uri}:{tag}", "manifest_digest": _digest(man_bytes)}


