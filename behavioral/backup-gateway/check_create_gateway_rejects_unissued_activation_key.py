"""create-gateway-rejects-unissued-activation-key."""
from __future__ import annotations

from behavioral_harness import tags

CHECK = "create-gateway-rejects-unissued-activation-key"
GROUP = "native-protocol"
SERVICES = ["backup-gateway"]


@tags("axis:rejection", "cap:c1", "concern:negative-classes", "plane:control")
def run(ctx) -> None:
    """CreateGateway with a well-formed activation key that no gateway issued fails with
    ValidationException and creates no gateway."""
    bg = ctx.client("backup-gateway")

    # Pattern-valid (per the model: ^[0-9a-zA-Z\-]+$, 1-50 chars) but never generated by any
    # real gateway appliance -- there is no activation record for AWS to redeem.
    fake_key = ctx.unique_name("sim2real-bgw-unissued-").replace("_", "-")
    display_name = ctx.unique_name("sim2real-bgw-gw-")

    got = _client_error(lambda: bg.create_gateway(
        ActivationKey=fake_key, GatewayDisplayName=display_name, GatewayType="BACKUP_VM"
    ))
    assert got == ("ValidationException", "The specified activation key was not found."), (
        f"unissued ActivationKey {fake_key!r}: expected ValidationException, got {got!r}"
    )
    names = _all_gateway_display_names(bg)
    assert display_name not in names, (
        f"rejected CreateGateway must not create a gateway, but {display_name!r} is listed: {names!r}"
    )

    # A second, independently-invalid key (fails the ActivationKey pattern outright) must land
    # in the same error family -- CreateGateway has no other client-error shape to report it in.
    bad_pattern_name = ctx.unique_name("sim2real-bgw-gw2-")
    bad_key = "not a valid key!!"
    pattern = _client_error(lambda: bg.create_gateway(
        ActivationKey=bad_key, GatewayDisplayName=bad_pattern_name,
        GatewayType="BACKUP_VM",
    ))
    pattern_message = (
        f"1 validation error detected: Value '{bad_key}' at 'activationKey' failed to satisfy "
        "constraint: Member must satisfy regular expression pattern: [0-9a-zA-Z\\-]+"
    )
    assert pattern == ("ValidationException", pattern_message), (
        f"pattern-invalid ActivationKey: expected ValidationException, got {pattern!r}"
    )
    names = _all_gateway_display_names(bg)
    assert bad_pattern_name not in names, (
        f"rejected CreateGateway must not create a gateway, but {bad_pattern_name!r} is listed: {names!r}"
    )


def _client_error(fn):
    """Call fn(); return its botocore error (code, message). An unexpected success raises,
    so accepting a request AWS refuses fails the check."""
    from botocore.exceptions import ClientError

    try:
        result = fn()
    except ClientError as e:
        err = e.response.get("Error", {})
        return err.get("Code"), err.get("Message")
    raise AssertionError(f"expected a ClientError, but the call SUCCEEDED and returned {result!r}")


def _all_gateway_display_names(bg) -> set[str]:
    names: set[str] = set()
    token = None
    while True:
        kwargs = {"NextToken": token} if token else {}
        resp = bg.list_gateways(**kwargs)
        names.update(g["GatewayDisplayName"] for g in resp.get("Gateways", []))
        token = resp.get("NextToken")
        if not token:
            break
    return names


if __name__ == "__main__":
    from fidelity_tests_runner import main
    main(run)
