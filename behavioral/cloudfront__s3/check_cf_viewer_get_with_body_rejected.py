"""cf-viewer-get-with-body-rejected."""
from __future__ import annotations

import json
import time

import requests

from behavioral_harness import tags

CHECK = "cf-viewer-get-with-body-rejected"
GROUP = "data-plane"
SERVICES = ["cloudfront", "s3"]

#: Marks a failure caused by an edge data plane that serves no traffic at all.
DATAPLANE_MARKER = "DATAPLANE_UNIMPLEMENTED"

MANAGED_CACHING_OPTIMIZED = "658327ea-f89d-4fab-a63d-7e88639e58f6"

#: CloudFront's own edge-generated error page for this refusal, fixed except for the Request ID
#: the edge mints for the request; everything between the prefix and the suffix is that ID.
_ERROR_BODY_PREFIX = (
    b'<!DOCTYPE HTML PUBLIC "-//W3C//DTD HTML 4.01 Transitional//EN" '
    b'"http://www.w3.org/TR/html4/loose.dtd">\n'
    b'<HTML><HEAD><META HTTP-EQUIV="Content-Type" CONTENT="text/html; charset=iso-8859-1">\n'
    b"<TITLE>ERROR: The request could not be satisfied</TITLE>\n"
    b"</HEAD><BODY>\n"
    b"<H1>403 ERROR</H1>\n"
    b"<H2>The request could not be satisfied.</H2>\n"
    b'<HR noshade size="1px">\n'
    b"Bad request.\n"
    b"We can't connect to the server for this app or website at this time. There might be too "
    b"much traffic or a configuration error. Try again later, or contact the app or website "
    b"owner.\n"
    b'<BR clear="all">\n'
    b"If you provide content to customers through CloudFront, you can find steps to troubleshoot "
    b"and help prevent this error by reviewing the CloudFront documentation.\n"
    b'<BR clear="all">\n'
    b'<HR noshade size="1px">\n'
    b"<PRE>\n"
    b"Generated by cloudfront (CloudFront)\n"
    b"Request ID: "
)
_ERROR_BODY_SUFFIX = b"\n</PRE>\n<ADDRESS>\n</ADDRESS>\n</BODY></HTML>"


def _poll_until(probe, predicate, *, timeout_s, interval_s=5.0, description="condition"):
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        last = probe()
        if predicate(last):
            return last
        time.sleep(interval_s)
    raise AssertionError(f"timed out waiting for {description} after {timeout_s}s (last: {last!r})")


def _wait_distribution_deployed(cf, dist_id, *, timeout_s=900.0, interval_s=10.0) -> str:
    """Poll GetDistribution until Status == 'Deployed'; return the ETag read at that moment."""
    holder = {"etag": ""}

    def probe() -> str:
        r = cf.get_distribution(Id=dist_id)
        holder["etag"] = r["ETag"]
        return r["Distribution"]["Status"]

    _poll_until(probe, lambda s: s == "Deployed", timeout_s=timeout_s, interval_s=interval_s,
                description=f"distribution {dist_id} to reach Deployed")
    return holder["etag"]


def _disable_and_delete_distribution(cf, dist_id) -> None:
    cfg_resp = cf.get_distribution_config(Id=dist_id)
    cfg = cfg_resp["DistributionConfig"]
    etag = cfg_resp["ETag"]
    if cfg.get("Enabled"):
        cfg["Enabled"] = False
        cf.update_distribution(Id=dist_id, IfMatch=etag, DistributionConfig=cfg)
    etag = _wait_distribution_deployed(cf, dist_id)
    cf.delete_distribution(Id=dist_id, IfMatch=etag)


def _delete_with_etag(get_fn, delete_fn, resource_id) -> None:
    delete_fn(Id=resource_id, IfMatch=get_fn(Id=resource_id)["ETag"])


def _empty_and_delete_bucket(s3, bucket) -> None:
    for page in s3.get_paginator("list_objects_v2").paginate(Bucket=bucket):
        keys = [{"Key": o["Key"]} for o in page.get("Contents", [])]
        if keys:
            failed = s3.delete_objects(Bucket=bucket, Delete={"Objects": keys}).get("Errors")
            if failed:
                raise RuntimeError(f"DeleteObjects left {len(failed)} object(s): {failed[:3]}")
    s3.delete_bucket(Bucket=bucket)


def _allow_cloudfront_oac(s3, bucket, dist_arn) -> None:
    s3.put_bucket_policy(Bucket=bucket, Policy=json.dumps({
        "Version": "2012-10-17",
        "Statement": [{
            "Sid": "AllowCloudFrontServicePrincipal",
            "Effect": "Allow",
            "Principal": {"Service": "cloudfront.amazonaws.com"},
            "Action": "s3:GetObject",
            "Resource": f"arn:aws:s3:::{bucket}/*",
            "Condition": {"StringEquals": {"AWS:SourceArn": dist_arn}},
        }],
    }))


@tags("axis:rejection", "cap:c1", "concern:data-plane", "concern:negative-classes",
      "dp:endpoint", "plane:data")
def run(ctx) -> None:
    """A viewer GET that carries a request body is refused at the edge with a 403 and no object
    bytes, while the same GET with no body still serves the object unchanged.
    """
    cf = ctx.client("cloudfront")
    s3 = ctx.client("s3")

    bucket = ctx.unique_name("sim2real-behav-cfgetbody-").lower()
    if ctx.region == "us-east-1":
        s3.create_bucket(Bucket=bucket)
    else:
        s3.create_bucket(Bucket=bucket, CreateBucketConfiguration={"LocationConstraint": ctx.region})
    ctx.on_cleanup(lambda: _empty_and_delete_bucket(ctx.client("s3"), bucket))

    key = "obj.txt"
    body = b"sim2real-cf-get-with-body-object"
    s3.put_object(Bucket=bucket, Key=key, Body=body, ContentType="text/plain")

    oac_id = cf.create_origin_access_control(OriginAccessControlConfig={
        "Name": ctx.unique_name("sim2real-behav-cfgetbody-oac-"),
        "OriginAccessControlOriginType": "s3",
        "SigningBehavior": "always",
        "SigningProtocol": "sigv4",
    })["OriginAccessControl"]["Id"]
    ctx.on_cleanup(lambda: _delete_with_etag(cf.get_origin_access_control,
                                             cf.delete_origin_access_control, oac_id))

    origin_id = "s3origin"
    dist = cf.create_distribution(DistributionConfig={
        "CallerReference": ctx.unique_name("sim2real-behav-cfgetbody-cr-"),
        "Comment": "sim2real cf-viewer-get-with-body-rejected",
        "Enabled": True,
        "Origins": {"Quantity": 1, "Items": [{
            "Id": origin_id,
            "DomainName": f"{bucket}.s3.{ctx.region}.amazonaws.com",
            "S3OriginConfig": {"OriginAccessIdentity": ""},
            "OriginAccessControlId": oac_id,
        }]},
        "DefaultCacheBehavior": {
            "TargetOriginId": origin_id,
            "ViewerProtocolPolicy": "allow-all",
            "CachePolicyId": MANAGED_CACHING_OPTIMIZED,
        },
    })["Distribution"]
    dist_id, domain = dist["Id"], dist["DomainName"]
    ctx.on_cleanup(lambda: _disable_and_delete_distribution(cf, dist_id))
    dist_arn = dist["ARN"]
    cf.tag_resource(Resource=dist_arn, Tags={"Items": [
        {"Key": "sim2real", "Value": "behavioral"},
    ]})

    _allow_cloudfront_oac(s3, bucket, dist_arn)
    _wait_distribution_deployed(cf, dist_id)

    url, route_headers = ctx.endpoint_route(f"{domain}/{key}")

    def get(**kw):
        try:
            return requests.get(url, headers=route_headers, timeout=15, verify=ctx.http_verify, **kw)
        except (requests.ConnectionError, requests.Timeout):
            return None

    # POSITIVE CONTROL first: the same object, same URL, no body.
    try:
        control = _poll_until(
            lambda: get(),
            lambda r: r is not None and r.status_code == 200,
            timeout_s=180, interval_s=10,
            description=f"200 fetching {url} with no body",
        )
    except AssertionError as exc:
        raise AssertionError(f"{DATAPLANE_MARKER}: {exc}") from exc
    assert control.content == body, f"control GET returned the wrong bytes: {control.content!r}"

    # BREAK ONE THING: the identical GET, now carrying a request body.
    refused = get(data=b"sim2real-get-body-payload")
    assert isinstance(refused, requests.Response), f"GET-with-body to {url} failed to connect: {refused!r}"
    assert refused.status_code == 403, (
        f"a GET request with a body answered {refused.status_code!r}, expected 403"
    )
    assert refused.headers.get("X-Cache") == "Error from cloudfront", (
        f"the 403 was not generated by the edge: X-Cache={refused.headers.get('X-Cache')!r}"
    )
    # The error page's body is fixed except for its own Request ID, which the edge makes up for
    # this request; startswith+endswith brackets everything the edge controls.
    assert refused.content.startswith(_ERROR_BODY_PREFIX) and refused.content.endswith(_ERROR_BODY_SUFFIX), (
        f"the 403 body does not match CloudFront's own error page: {refused.content!r}"
    )
    assert body not in refused.content, "the GET-with-body refusal leaked the object's bytes"

    # The refusal changed nothing: the same URL still serves the object with no body.
    again = get()
    assert isinstance(again, requests.Response) and again.status_code == 200, (
        f"GET with no body after the refusal returned {again!r}"
    )
    assert again.content == body, "the object served after the refusal differs from the upload"


if __name__ == "__main__":
    from fidelity_tests_runner import main
    main(run)
