def _deployment_zip():
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for arc, b64 in _B64.items():
            raw = base64.b64decode(b64)
            got = hashlib.sha256(raw).hexdigest()
            assert got == _SHA256[arc], (
                f"embedded artifact {arc!r} is sha256 {got!r}, pinned {_SHA256[arc]!r} — the "
                f"assembly under test is not the bytes this check was verified against"
            )
            zf.writestr(arc, raw)
        zf.writestr("Probe.runtimeconfig.json", _RUNTIME_CONFIG)
        zf.writestr("Probe.deps.json", _DEPS_JSON)
    return buf.getvalue()


_EXEC_ROLES = {}


def _exec_role_arn(ctx):
    """An execution role this check creates, shared by every function it deploys."""
    cached = _EXEC_ROLES.get(id(ctx))
    if cached is not None and cached[0] is ctx:
        return cached[1]
    iam = ctx.client("iam")
    role_name = ctx.unique_name("sim2real-behav-role-")
    trust = {
        "Version": "2012-10-17",
        "Statement": [
            {"Effect": "Allow", "Principal": {"Service": "lambda.amazonaws.com"}, "Action": "sts:AssumeRole"}
        ],
    }
    arn = iam.create_role(
        RoleName=role_name,
        AssumeRolePolicyDocument=json.dumps(trust),
        Tags=[{"Key": "sim2real", "Value": CHECK}],
    )["Role"]["Arn"]
    ctx.on_cleanup(_teardown(lambda: iam.delete_role(RoleName=role_name), "NoSuchEntity"))
    partition = ctx.client("sts").get_caller_identity()["Arn"].split(":")[1]
    policy_arn = f"arn:{partition}:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"
    iam.attach_role_policy(RoleName=role_name, PolicyArn=policy_arn)
    ctx.on_cleanup(_teardown(
        lambda: iam.detach_role_policy(RoleName=role_name, PolicyArn=policy_arn), "NoSuchEntity"
    ))
    _EXEC_ROLES[id(ctx)] = (ctx, arn)
    return arn


def _create_function(lam, kwargs, timeout_s=90):
    """CreateFunction, retried while a freshly created role is not yet assumable by Lambda."""
    deadline = time.monotonic() + timeout_s
    while True:
        try:
            return lam.create_function(**kwargs)
        except ClientError as exc:
            err = exc.response.get("Error", {})
            propagating = (
                err.get("Code") == "InvalidParameterValueException"
                and "cannot be assumed by Lambda" in err.get("Message", "")
            )
            if not propagating or time.monotonic() >= deadline:
                raise
            time.sleep(3.0)


def _cleanup_fn(ctx, lam, name):
    try:
        lam.delete_function(FunctionName=name)
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "ResourceNotFoundException":
            raise
    _reap_log_group(ctx.client("logs"), f"/aws/lambda/{name}")


def _poll(probe, timeout_s, interval_s=2.0):
    deadline = time.monotonic() + timeout_s
    while time.monotonic() < deadline:
        got = probe()
        if got:
            return got
        time.sleep(interval_s)
    return None


def _wait_active(lam, fn, timeout_s=300):
    def _probe():
        cfg = lam.get_function_configuration(FunctionName=fn)
        if cfg["State"] == "Failed":
            raise AssertionError(f"{fn} entered State=Failed: {cfg.get('StateReason')!r}")
        if cfg["State"] == "Active" and cfg.get("LastUpdateStatus") in (None, "Successful"):
            return cfg
        return None

    cfg = _poll(_probe, timeout_s)
    assert cfg is not None, f"{fn} did not reach State=Active within {timeout_s}s"
    return cfg


def _raw_invoke(lam, fn, payload, qualifier=None):
    kwargs = dict(FunctionName=fn, LogType="Tail", Payload=payload)
    if qualifier:
        kwargs["Qualifier"] = qualifier
    resp = lam.invoke(**kwargs)
    raw = resp["Payload"].read()
    assert resp["StatusCode"] == 200, f"{fn}: StatusCode {resp['StatusCode']!r} {raw!r}"
    return resp.get("FunctionError"), raw


def _ok_json(lam, fn, payload_obj, qualifier=None):
    err, raw = _raw_invoke(lam, fn, json.dumps(payload_obj).encode(), qualifier=qualifier)
    assert err is None, f"{fn} invoke of {payload_obj!r} failed: FunctionError={err!r} raw={raw!r}"
    return json.loads(raw), raw


def _err_json(lam, fn, payload_obj):
    err, raw = _raw_invoke(lam, fn, json.dumps(payload_obj).encode())
    assert err == "Unhandled", (
        f"{fn} invoke of {payload_obj!r} was expected to fail with FunctionError=='Unhandled' but "
        f"returned FunctionError={err!r} and raw {raw!r}"
    )
    return json.loads(raw), raw


@tags("axis:happy-path", "cap:c3", "concern:negative-classes", "concern:data-plane", "dp:api", "plane:data")
def run(ctx) -> None:
    """An exception thrown from a class library handler's constructor is an init error: every invocation reports it wrapped in .NET reflection's TargetInvocationException, with the customer's own exception nested under its 'cause', never surfaced as the customer's own errorType directly, and repeats identically because the constructor runs again each time.

    Reference: https://docs.aws.amazon.com/lambda/latest/dg/csharp-handler.html#csharp-class-library-handlers"""

    lam = ctx.client("lambda")
    role = _exec_role_arn(ctx)
    code = _deployment_zip()

    # positive control: a sibling function from the same package, a working handler
    good_fn = ctx.unique_name("sim2real-behav-dotnetctorok-")
    _create_function(lam, dict(
        FunctionName=good_fn, Runtime="dotnet10", Handler="Probe::Probe.StringHandler::Handle",
        Role=role, Code={"ZipFile": code}, MemorySize=512, Timeout=30, Tags={"sim2real": CHECK},
    ))
    ctx.on_cleanup(lambda: _cleanup_fn(ctx, lam, good_fn))
    _wait_active(lam, good_fn)
    good_body, _ = _ok_json(lam, good_fn, "ok")
    assert good_body.startswith("echo:ok:"), f"the control function did not run: {good_body!r}"

    bad_fn = ctx.unique_name("sim2real-behav-dotnetctorbad-")
    _create_function(lam, dict(
        FunctionName=bad_fn, Runtime="dotnet10", Handler="Probe::Probe.ThrowingCtorHandler::Handle",
        Role=role, Code={"ZipFile": code}, MemorySize=512, Timeout=30, Tags={"sim2real": CHECK},
    ))
    ctx.on_cleanup(lambda: _cleanup_fn(ctx, lam, bad_fn))
    _wait_active(lam, bad_fn)

    for attempt in range(2):
        body, _ = _err_json(lam, bad_fn, "x")
        assert body["errorType"] == "TargetInvocationException", (
            f"attempt {attempt}: a constructor exception reported errorType "
            f"{body.get('errorType')!r}, not .NET reflection's TargetInvocationException wrapper"
        )
        assert body["errorMessage"] == "Exception has been thrown by the target of an invocation.", (
            f"attempt {attempt}: errorMessage was {body['errorMessage']!r}"
        )
        cause = body.get("cause")
        assert cause is not None, f"attempt {attempt}: no nested cause carrying the real exception"
        assert cause["errorType"] == "InvalidOperationException", (
            f"attempt {attempt}: cause.errorType was {cause.get('errorType')!r}"
        )
        assert cause["errorMessage"] == "probe-constructor-failure", (
            f"attempt {attempt}: cause.errorMessage was {cause['errorMessage']!r}"
        )

    # the sibling function, built from the same package, is unaffected
    good_body2, _ = _ok_json(lam, good_fn, "still-ok")
    assert good_body2.startswith("echo:still-ok:"), f"the control function broke too: {good_body2!r}"


if __name__ == "__main__":
    from fidelity_tests_runner import main
    main(run)
