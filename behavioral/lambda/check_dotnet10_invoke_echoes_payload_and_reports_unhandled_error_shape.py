def _deployment_zip() -> bytes:
    """The deployment package built from the embedded assembly, its SHA-256 re-checked."""
    buf = io.BytesIO()
    with zipfile.ZipFile(buf, "w", zipfile.ZIP_DEFLATED) as zf:
        for arc, b64 in _B64.items():
            raw = base64.b64decode(b64)
            got = hashlib.sha256(raw).hexdigest()
            assert got == _SHA256[arc], (
                f"embedded artifact {arc!r} is sha256 {got!r}, pinned {_SHA256[arc]!r} — the "
                f"assembly under test is not the one this check was verified against"
            )
            zf.writestr(arc, raw)
    return buf.getvalue()


def _teardown(undo, *not_found: str):
    """A cleanup running ``undo()`` where a failed delete raises; only ``not_found`` means gone."""

    def run_undo() -> None:
        try:
            undo()
        except ClientError as exc:
            if exc.response["Error"]["Code"] in not_found:
                return
            raise

    return run_undo


def _reap_log_group(logs, name: str, *, reads: int = 3, interval_s: float = 4.0,
                    budget_s: float = 60.0) -> None:
    """Delete log group ``name`` until ``reads`` consecutive reads find it absent."""
    deadline = time.monotonic() + budget_s
    absent = 0
    while absent < reads:
        groups = logs.describe_log_groups(logGroupNamePrefix=name)["logGroups"]
        if any(g["logGroupName"] == name for g in groups):
            absent = 0
            try:
                logs.delete_log_group(logGroupName=name)
            except ClientError as exc:
                if exc.response["Error"]["Code"] != "ResourceNotFoundException":
                    raise
        else:
            absent += 1
        if absent < reads:
            if time.monotonic() > deadline:
                raise AssertionError(
                    f"log group {name!r} still present after {budget_s}s of deletes"
                )
            time.sleep(interval_s)


def _role(ctx) -> str:
    """An execution role this check creates and tears down."""
    iam = ctx.client("iam")
    name = ctx.unique_name("sim2real-behav-dnet10-")
    arn = iam.create_role(
        RoleName=name, AssumeRolePolicyDocument=json.dumps(_TRUST),
        Tags=[{"Key": "sim2real", "Value": CHECK}],
    )["Role"]["Arn"]
    ctx.on_cleanup(_teardown(lambda: iam.delete_role(RoleName=name), "NoSuchEntity"))
    policy = "arn:aws:iam::aws:policy/service-role/AWSLambdaBasicExecutionRole"
    iam.attach_role_policy(RoleName=name, PolicyArn=policy)
    ctx.on_cleanup(_teardown(
        lambda: iam.detach_role_policy(RoleName=name, PolicyArn=policy), "NoSuchEntity"))
    return arn


def _wait_active(lam, fn: str, timeout_s: float = 90.0) -> None:
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        last = lam.get_function_configuration(FunctionName=fn)
        if last["State"] == "Failed":
            raise AssertionError(f"{fn} entered Failed: {last.get('StateReason')!r}")
        if last["State"] == "Active":
            return
        time.sleep(1.0)
    raise AssertionError(f"{fn} did not become Active within {timeout_s}s; last={last!r}")


def _deploy(ctx, lam, role: str, handler: str, label: str) -> str:
    """Create a function from the shared embedded assembly, pointed at one of its two handlers."""
    fn = ctx.unique_name(f"sim2real-behav-dnet10-{label}-")
    logs = ctx.client("logs")
    ctx.on_cleanup(lambda: _reap_log_group(logs, f"/aws/lambda/{fn}"))
    deadline = time.monotonic() + 90
    while True:
        try:
            lam.create_function(
                FunctionName=fn, Runtime=_RUNTIME, Handler=handler, Role=role,
                Code={"ZipFile": _deployment_zip()}, MemorySize=256, Timeout=10,
                Tags={"sim2real": CHECK},
            )
            break
        except ClientError as exc:
            if "cannot be assumed" in exc.response["Error"].get("Message", "") \
                    and time.monotonic() < deadline:
                time.sleep(3)
                continue
            raise
    ctx.on_cleanup(_teardown(lambda: lam.delete_function(FunctionName=fn),
                             "ResourceNotFoundException"))
    _wait_active(lam, fn)
    return fn


def _invoke(lam, fn: str, payload: bytes) -> dict:
    """A RequestResponse invoke, returning status, function error, executed version and body."""
    resp = lam.invoke(FunctionName=fn, InvocationType="RequestResponse", Payload=payload)
    return {
        "status": resp["StatusCode"],
        "error": resp.get("FunctionError"),
        "version": resp.get("ExecutedVersion"),
        "body": json.loads(resp["Payload"].read()),
    }


@tags("axis:happy-path", "cap:c3", "concern:data-plane", "concern:representation", "dp:api",
      "plane:data")
def run(ctx) -> None:
    """A dotnet10 RequestResponse invoke returns StatusCode 200, ExecutedVersion $LATEST and the
    exact event plus AWS_EXECUTION_ENV; a handler that throws reports FunctionError Unhandled with
    the thrown exception's own type and message.

    Reference: https://docs.aws.amazon.com/lambda/latest/dg/lambda-runtimes.html
    Reference: https://docs.aws.amazon.com/lambda/latest/dg/csharp-exceptions.html
    """
    lam = ctx.client("lambda")
    role = _role(ctx)

    echo_fn = _deploy(ctx, lam, role, "function::Sim2RealFn.Function::EchoHandler", "echo")
    payload = {"a": 1, "b": "two", "nonce": ctx.unique_name("n-")}
    r = _invoke(lam, echo_fn, json.dumps(payload).encode())
    assert r["status"] == 200, f"echo: StatusCode was {r['status']!r}, expected 200"
    assert r["error"] is None, f"echo: unexpected FunctionError={r['error']!r}, body={r['body']!r}"
    assert r["version"] == "$LATEST", f"echo: ExecutedVersion was {r['version']!r}, expected '$LATEST'"
    want = dict(payload)
    want["runtime"] = f"AWS_Lambda_{_RUNTIME}"
    assert r["body"] == want, f"echo: body was {r['body']!r}, expected exactly {want!r}"

    raise_fn = _deploy(ctx, lam, role, "function::Sim2RealFn.Function::RaiseHandler", "raise")
    nonce = ctx.unique_name("boom-")
    r = _invoke(lam, raise_fn, json.dumps({"message": nonce}).encode())
    assert r["status"] == 200, f"raise: StatusCode was {r['status']!r}, expected 200 even on error"
    assert r["error"] == "Unhandled", f"raise: FunctionError was {r['error']!r}, expected 'Unhandled'"
    assert r["body"].get("errorType") == "InvalidOperationException", (
        f"raise: errorType was {r['body'].get('errorType')!r}, expected "
        f"'InvalidOperationException'"
    )
    assert r["body"].get("errorMessage") == nonce, (
        f"raise: errorMessage was {r['body'].get('errorMessage')!r}, expected {nonce!r}"
    )
    trace = r["body"].get("stackTrace")
    assert isinstance(trace, list) and len(trace) > 0, (
        f"raise: stackTrace was {trace!r}, expected a non-empty list"
    )


if __name__ == "__main__":
    from fidelity_tests_runner import main
    main(run)
