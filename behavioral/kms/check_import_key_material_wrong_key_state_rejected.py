"""import-key-material-wrong-key-state-rejected."""
from __future__ import annotations

import os
import time

from behavioral_harness import tags

CHECK = "import-key-material-wrong-key-state-rejected"
GROUP = "error-semantics"
SERVICES = ["kms"]


def _error(fn):
    """Call fn(); return its botocore (Error.Code, Error.Message). An unexpected SUCCESS raises, because
    an emulator ACCEPTING an import real AWS refuses is the strongest signal available."""
    from botocore.exceptions import ClientError

    try:
        result = fn()
    except ClientError as exc:
        return exc.response["Error"]["Code"], exc.response["Error"].get("Message", "")
    raise AssertionError(f"expected rejection, but the call SUCCEEDED and returned {result!r}")


def _poll_until(probe, predicate, *, timeout_s=60.0, interval_s=3.0):
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        last = probe()
        if predicate(last):
            return last
        time.sleep(interval_s)
    raise AssertionError(f"condition not met within {timeout_s}s (last={last!r})")


@tags("axis:rejection", "cap:c1", "concern:data-plane", "concern:negative-classes", "dp:api", "plane:control", "plane:data")
def run(ctx) -> None:
    """ImportKeyMaterial into an AWS_KMS-origin key fails with UnsupportedOperationException and the exact message,
    leaving the key Enabled and usable, while the same import into an EXTERNAL-origin key moves it from
    PendingImport to Enabled."""
    kms = ctx.client("kms")

    key = kms.create_key(
        Description=ctx.unique_name("sim2real-behav-kms-"),
        KeyUsage="ENCRYPT_DECRYPT",
        KeySpec="SYMMETRIC_DEFAULT",
        # Origin defaults to AWS_KMS -> key material is generated by KMS and the key
        # comes up Enabled immediately; it is never in PendingImport state.
        Tags=[{"TagKey": "sim2real", "TagValue": "kms-import-key-material-wrong-key-state"}],
    )["KeyMetadata"]
    key_id = key["KeyId"]
    ctx.on_cleanup(lambda: kms.schedule_key_deletion(KeyId=key_id, PendingWindowInDays=7))
    assert key["Origin"] == "AWS_KMS"
    assert key["KeyState"] == "Enabled"

    code, message = _error(
        lambda: kms.import_key_material(
            KeyId=key_id,
            ImportToken=b"not-a-real-import-token",
            EncryptedKeyMaterial=b"not-real-encrypted-key-material",
        )
    )
    assert code == "UnsupportedOperationException", (
        f"expected UnsupportedOperationException, got {code}"
    )
    expected_message = f"{key['Arn']} origin is AWS_KMS which is not valid for this operation."
    assert message == expected_message, f"expected {expected_message!r}, got {message!r}"

    # Effect absent: the rejected import attempt did not change the key's state/origin.
    described = kms.describe_key(KeyId=key_id)["KeyMetadata"]
    assert described["KeyState"] == "Enabled"
    assert described["Origin"] == "AWS_KMS"

    # Positive control (native key): the key is still fully usable for its native crypto ops.
    ciphertext = kms.encrypt(KeyId=key_id, Plaintext=b"control-plaintext")["CiphertextBlob"]
    plaintext = kms.decrypt(KeyId=key_id, CiphertextBlob=ciphertext)["Plaintext"]
    assert plaintext == b"control-plaintext"

    # Positive control (same operation): without a control on ImportKeyMaterial itself, "rejects
    # import against a non-PendingImport key" is indistinguishable from "rejects every import".
    # The ONLY thing that changes is Origin=EXTERNAL and a correctly wrapped token/material -- the
    # exact same call succeeds and the key becomes Enabled.
    from cryptography.hazmat.primitives import hashes, serialization
    from cryptography.hazmat.primitives.asymmetric import padding

    external_key = kms.create_key(
        Description=ctx.unique_name("sim2real-behav-kms-external-"),
        KeyUsage="ENCRYPT_DECRYPT",
        KeySpec="SYMMETRIC_DEFAULT",
        Origin="EXTERNAL",
        Tags=[{"TagKey": "sim2real", "TagValue": "kms-import-key-material-wrong-key-state"}],
    )["KeyMetadata"]
    external_key_id = external_key["KeyId"]
    ctx.on_cleanup(lambda: kms.schedule_key_deletion(KeyId=external_key_id, PendingWindowInDays=7))
    assert external_key["KeyState"] == "PendingImport", external_key["KeyState"]

    params = kms.get_parameters_for_import(
        KeyId=external_key_id,
        WrappingAlgorithm="RSAES_OAEP_SHA_256",
        WrappingKeySpec="RSA_2048",
    )
    public_key = serialization.load_der_public_key(params["PublicKey"])
    wrapped = public_key.encrypt(
        os.urandom(32),
        padding.OAEP(
            mgf=padding.MGF1(algorithm=hashes.SHA256()),
            algorithm=hashes.SHA256(),
            label=None,
        ),
    )
    kms.import_key_material(
        KeyId=external_key_id,
        ImportToken=params["ImportToken"],
        EncryptedKeyMaterial=wrapped,
        ExpirationModel="KEY_MATERIAL_DOES_NOT_EXPIRE",
    )
    imported = _poll_until(
        lambda: kms.describe_key(KeyId=external_key_id)["KeyMetadata"],
        lambda d: d["KeyState"] != "PendingImport",
    )
    assert imported["KeyState"] == "Enabled", imported["KeyState"]


if __name__ == "__main__":
    from fidelity_tests_runner import main

    main(run)
