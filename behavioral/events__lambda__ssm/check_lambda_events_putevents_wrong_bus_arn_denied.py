"""lambda-events-putevents-wrong-bus-arn-denied."""

from __future__ import annotations

import json
import textwrap
import time
import zipfile
from io import BytesIO
from typing import Any

from botocore.exceptions import ClientError

from behavioral_harness import tags

CHECK = "lambda-events-putevents-wrong-bus-arn-denied"

GROUP = "overly-permissive"

SERVICES = ["events", "lambda", "ssm"]


def _payload(result: dict) -> dict:
    """Return an invocation's parsed payload, failing loudly on a Lambda error.

    ``invoke_lambda`` reports a handler crash via ``result["error"]`` while
    still returning a payload (the runtime's error envelope). Surfacing that
    here turns an opaque ``KeyError`` in a downstream assertion into the actual
    Lambda error message.
    """
    assert not result.get("error"), (
        f"Lambda invocation failed with {result['error']}: "
        f"{result.get('payload') or result.get('payload_raw')}"
    )
    payload = result.get("payload")
    assert isinstance(payload, dict), f"handler did not return a JSON object: {result}"
    return payload


@tags("axis:rejection", "cap:c3", "cap:c7", "concern:data-plane", "concern:negative-classes", "dp:api", "plane:data")
def run(ctx) -> None:
    """A role scoped to one event bus ARN puts events on that bus but is denied on another with
    AccessDeniedException and its exact message; widening the policy to the second bus makes the
    identical call succeed."""
    events = ctx.client("events")
    iam = ctx.client("iam")
    lam = ctx.client("lambda")
    allowed_bus = ctx.unique_name("bus-allowed-")
    other_bus = ctx.unique_name("bus-other-")
    events.create_event_bus(Name=allowed_bus)
    events.create_event_bus(Name=other_bus)
    ctx.on_cleanup(lambda: ctx.client("events").delete_event_bus(Name=allowed_bus))
    ctx.on_cleanup(lambda: ctx.client("events").delete_event_bus(Name=other_bus))

    code = """
import boto3
from botocore.exceptions import ClientError
events = boto3.client("events")

def lambda_handler(event, context):
    try:
        resp = events.put_events(Entries=[{
            "Source": "integration.wrongbus", "DetailType": "Test", "Detail": "{}",
            "EventBusName": event["bus"],
        }])
        failed = resp.get("FailedEntryCount", 0)
        if failed:
            entry = (resp.get("Entries") or [{}])[0]
            return {
                "ok": False, "denied": True, "mode": "failed_entry",
                "code": entry.get("ErrorCode") or "UnknownEntryError",
            }
        return {"ok": True, "denied": False, "mode": "accepted", "code": None}
    except ClientError as e:
        return {
            "ok": False, "denied": True, "mode": "client_error",
            "code": e.response["Error"]["Code"],
            "message": e.response["Error"].get("Message", ""),
        }
"""
    account = ctx.client("sts").get_caller_identity()["Account"]
    allowed_arn = f"arn:aws:events:{ctx.region}:{account}:event-bus/{allowed_bus}"
    other_arn = f"arn:aws:events:{ctx.region}:{account}:event-bus/{other_bus}"
    fn = _create_lambda(
        ctx, code, permissions=[{"Action": ["events:PutEvents"], "Resource": allowed_arn}]
    )
    role_name = lam.get_function_configuration(FunctionName=fn["name"])["Role"].rsplit(
        "/", 1
    )[-1]

    # --- Positive control: the role's own scope works before anything is concluded from a denial.
    allowed_result = _payload(_invoke_lambda(ctx, fn["name"], {"bus": allowed_bus}))
    assert allowed_result["ok"] is True and allowed_result["denied"] is False, (
        f"expected PutEvents to the in-scope bus to succeed, got {allowed_result}"
    )

    # --- Break exactly one thing: the identical call, targeting the bus the policy does not name.
    denied_result = _payload(_invoke_lambda(ctx, fn["name"], {"bus": other_bus}))
    assert denied_result["denied"] is True, (
        f"expected AccessDenied for wrong event bus, got {denied_result}"
    )
    assert denied_result["mode"] == "client_error" and denied_result["code"] == "AccessDeniedException", (
        f"expected PutEvents to the out-of-scope bus to raise AccessDeniedException, got {denied_result}"
    )
    expected = (
        f"User: arn:aws:sts::{account}:assumed-role/{role_name}/{fn['name']} is not authorized to "
        f"perform: events:PutEvents on resource: {other_arn} because no identity-based policy allows "
        "the events:PutEvents action"
    )
    assert denied_result["message"] == expected, f"expected {expected!r}, got {denied_result}"

    # --- Restore: widen the policy to cover the second bus too; propagate; retry the identical call.
    iam.put_role_policy(
        RoleName=role_name,
        PolicyName="inline",
        PolicyDocument=json.dumps({
            "Version": "2012-10-17",
            "Statement": [
                {
                    "Effect": "Allow",
                    "Action": [
                        "logs:CreateLogGroup",
                        "logs:CreateLogStream",
                        "logs:PutLogEvents",
                    ],
                    "Resource": "arn:aws:logs:*:*:*",
                },
                {
                    "Effect": "Allow",
                    "Action": ["events:PutEvents"],
                    "Resource": [allowed_arn, other_arn],
                },
            ],
        }),
    )
    restored_result = _poll_until(
        lambda: _payload(_invoke_lambda(ctx, fn["name"], {"bus": other_bus})),
        lambda p: p.get("denied") is False,
        timeout_s=60.0,
        interval_s=5.0,
        description="widened policy permits PutEvents to the previously-denied bus",
    )
    assert restored_result["ok"] is True and restored_result["denied"] is False, (
        "widening the policy to include the second bus must restore the identical call, got "
        f"{restored_result}"
    )


_XSVC_PREFIX = "sim2real-xsvc-"

_MANAGED_TAG_KEY = "sim2real:managed"


def _xsvc_resource_tags() -> dict[str, str]:
    return {_MANAGED_TAG_KEY: "true", "sim2real:prefix": _XSVC_PREFIX.rstrip("-")}


def _xsvc_tags_kv() -> list[dict[str, str]]:
    return [{"Key": k, "Value": v} for k, v in _xsvc_resource_tags().items()]


def _xname(ctx: Any, kind: str) -> str:
    """A unique, prefix-tagged resource name: sim2real-xsvc-<kind>-<uuid>."""
    return ctx.unique_name(f"{_XSVC_PREFIX}{kind}-")


def _poll_until(
    probe, predicate, *, timeout_s=60.0, interval_s=1.0, description="condition"
):
    """Poll probe() until predicate(result) is truthy; return the final result (raises on timeout)."""
    deadline = time.monotonic() + timeout_s
    last = None
    while time.monotonic() < deadline:
        last = probe()
        if predicate(last):
            return last
        time.sleep(interval_s)
    raise AssertionError(
        f"{description} not met within {timeout_s}s. Last result: {last!r}"
    )


def _create_role(
    ctx, trust_service, inline_policy=None, managed_policies=None
) -> dict[str, str]:
    """Create an IAM role and register its (policy-detach-then-delete) teardown. Returns {name,arn}."""
    iam = ctx.client("iam")
    role_name = _xname(ctx, f"role-{trust_service.split('.')[0]}")
    trust = {
        "Version": "2012-10-17",
        "Statement": [
            {
                "Effect": "Allow",
                "Principal": {"Service": trust_service},
                "Action": "sts:AssumeRole",
            }
        ],
    }
    resp = iam.create_role(
        RoleName=role_name,
        AssumeRolePolicyDocument=json.dumps(trust),
        Path="/sim2real/",
        Tags=_xsvc_tags_kv(),
    )
    ctx.on_cleanup(lambda: _delete_role(ctx, role_name))
    for policy_arn in managed_policies or []:
        iam.attach_role_policy(RoleName=role_name, PolicyArn=policy_arn)
    if inline_policy:
        iam.put_role_policy(
            RoleName=role_name,
            PolicyName="inline",
            PolicyDocument=json.dumps(inline_policy),
        )
    # IAM role trust/permission propagation is bounded by _create_function_with_retry's own
    # retry-on-"cannot be assumed" loop below, not by an unconditional wait here.
    return {"name": role_name, "arn": resp["Role"]["Arn"]}


def _delete_role(ctx, role_name: str) -> None:
    """IAM roles need every attached + inline policy removed before deletion."""
    iam = ctx.client("iam")
    try:
        for p in iam.list_attached_role_policies(RoleName=role_name).get(
            "AttachedPolicies", []
        ):
            iam.detach_role_policy(RoleName=role_name, PolicyArn=p["PolicyArn"])
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "NoSuchEntity":
            raise
    try:
        for pname in iam.list_role_policies(RoleName=role_name).get("PolicyNames", []):
            iam.delete_role_policy(RoleName=role_name, PolicyName=pname)
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "NoSuchEntity":
            raise
    try:
        iam.delete_role(RoleName=role_name)
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "NoSuchEntity":
            raise


def _delete_log_group_if_present(ctx, log_group: str) -> None:
    try:
        ctx.client("logs").delete_log_group(logGroupName=log_group)
    except ClientError as exc:
        if exc.response["Error"]["Code"] != "ResourceNotFoundException":
            raise


def _wait_function_active(ctx, name: str, timeout_s: float = 60) -> None:
    lam = ctx.client("lambda")
    _poll_until(
        lambda: lam.get_function_configuration(FunctionName=name),
        lambda r: r.get("State") == "Active",
        timeout_s=timeout_s,
        interval_s=2.0,
        description=f"Lambda {name} active",
    )


def _create_function_with_retry(
    ctx, handler_code, role_arn, env, timeout=30, memory=128, runtime="python3.12"
) -> dict[str, str]:
    """Create a Lambda, retrying through the IAM role-propagation window, then wait until Active.
    Registers the function's teardown (LIFO-before its role, since the role was registered first)."""
    name = _xname(ctx, "fn")
    lam = ctx.client("lambda")
    # Normalize inline handler source: dedent (checks often embed indented triple-quoted code) and
    # bind to the fixed entrypoint — the Handler is "lambda_function.lambda_handler", but inline code
    # is conventionally written as `def handler(event, context)`. Without a lambda_handler symbol the
    # function fails at runtime with Runtime.HandlerNotFound before any behavior is exercised. Both are
    # no-ops for code that's already column-0 and defines lambda_handler.
    handler_code = textwrap.dedent(handler_code)
    if "def lambda_handler" not in handler_code and "def handler" in handler_code:
        handler_code = handler_code.rstrip() + "\n\nlambda_handler = handler\n"
    zip_buf = BytesIO()
    with zipfile.ZipFile(zip_buf, "w", zipfile.ZIP_DEFLATED) as zf:
        zf.writestr("lambda_function.py", handler_code)
    kwargs: dict[str, Any] = {
        "FunctionName": name,
        "Runtime": runtime,
        "Role": role_arn,
        "Handler": "lambda_function.lambda_handler",
        "Code": {"ZipFile": zip_buf.getvalue()},
        "Timeout": timeout,
        "MemorySize": memory,
        "Tags": dict(_xsvc_resource_tags()),
    }
    if env:
        kwargs["Environment"] = {"Variables": env}
    deadline = time.monotonic() + 30
    last_err = None
    while time.monotonic() < deadline:
        try:
            resp = lam.create_function(**kwargs)
            ctx.on_cleanup(lambda: lam.delete_function(FunctionName=name))
            # The function creates /aws/lambda/<name> on first invoke and the group outlives the
            # function, so delete it too; a function never invoked has no log group to delete.
            ctx.on_cleanup(lambda: _delete_log_group_if_present(ctx, f"/aws/lambda/{name}"))
            _wait_function_active(ctx, name)
            return {"name": name, "arn": resp["FunctionArn"]}
        except ClientError as e:
            if "cannot be assumed" in str(e) or "InvalidParameterValue" in str(e):
                last_err = e
                time.sleep(3)
                continue
            raise
    raise last_err or RuntimeError(f"Failed to create Lambda {name}")


def _create_lambda(
    ctx,
    handler_code,
    permissions=None,
    env=None,
    timeout=30,
    memory=128,
    runtime="python3.12",
) -> dict[str, str]:
    """Create a Lambda with an execution role scoped to `permissions` (a list of IAM statement
    fragments like [{"Action": ["sqs:SendMessage"], "Resource": queue_arn}]); logs are always
    allowed. Role + function each register their own teardown (function torn down first, LIFO).
    Returns {name,arn}."""
    statements = [
        {
            "Effect": "Allow",
            "Action": [
                "logs:CreateLogGroup",
                "logs:CreateLogStream",
                "logs:PutLogEvents",
            ],
            "Resource": "arn:aws:logs:*:*:*",
        }
    ]
    for perm in permissions or []:
        actions = (
            perm["Action"] if isinstance(perm["Action"], list) else [perm["Action"]]
        )
        resource = (
            perm["Resource"]
            if isinstance(perm["Resource"], list)
            else [perm["Resource"]]
        )
        statements.append({"Effect": "Allow", "Action": actions, "Resource": resource})
    role = _create_role(
        ctx,
        "lambda.amazonaws.com",
        inline_policy={"Version": "2012-10-17", "Statement": statements},
    )
    return _create_function_with_retry(
        ctx, handler_code, role["arn"], env or {}, timeout, memory, runtime
    )


def _invoke_lambda(ctx, name: str, payload: dict | None = None) -> dict[str, Any]:
    """Invoke a Lambda synchronously; return {status_code[, error], payload|payload_raw}."""
    resp = ctx.client("lambda").invoke(
        FunctionName=name,
        InvocationType="RequestResponse",
        Payload=json.dumps(payload or {}).encode(),
    )
    body = resp["Payload"].read()
    result: dict[str, Any] = {"status_code": resp["StatusCode"]}
    if resp.get("FunctionError"):
        result["error"] = resp["FunctionError"]
    try:
        result["payload"] = json.loads(body)
    except (json.JSONDecodeError, ValueError):
        result["payload_raw"] = body.decode("utf-8", errors="replace")
    return result


